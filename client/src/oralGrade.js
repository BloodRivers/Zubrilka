import { aiJSON } from "./api/ai";

export async function gradeOral(transcript, criteria, metrics = null) {
  const rules = [
    "items — по одному на каждый критерий, points из его шкалы.",
    "total = сумма points по всем критериям.",
  ];
  if (criteria.task === 2) {
    rules.push(
      "Задание 2: пункты плана «Вопрос N» (их ровно столько, сколько пунктов в задании); за каждый такой пункт начисляй 1 балл, только если по нему задан прямой вопрос с правильной грамматической формой; незаданный или грамматически непрямой вопрос — 0 баллов."
    );
  }
  if (criteria.task === 3) {
    rules.push(
      "Задание 3 (интервью): в тексте запроса ответы идут блоками «Вопрос N — <текст вопроса> / Ответ: <текст ответа>». По критерию «Вопрос N» ставь 1 балл, только если этот ответ полный и точный (не менее 2 фраз) и отвечает именно на этот вопрос; пустой ответ, ответ не по теме или короче 2 фраз — 0 баллов."
    );
  }
  if (criteria.criteria?.some((c) => /Решение коммуникативной задачи/.test(c.name))) {
    rules.unshift("Если по критерию «Решение коммуникативной задачи» начислено 0 баллов, то total = 0 (всё задание — 0).");
  }
  const system = [
    "Ты — эксперт ЕГЭ по устной части английского языка.",
    "Расшифровка устного ответа ученика приходит в тексте запроса.",
    "Оцени ответ строго по критериям из запроса (JSON).",
    "Ответь строго в JSON такого вида:",
    '{"total": <число>, "max": <число>, "items": [{"name": "<критерий>", "points": <число>, "max": <число>, "comment": "<краткое обоснование>"}], "summary": "<1-2 предложения: главные замечания и что улучшить>"}',
    "Правила:",
    ...rules.map((r, i) => `${i + 1}. ${r}`),
  ].join("\n");
  const prompt = [
    `Задание №${criteria.task}.`,
    `Критерии: ${JSON.stringify(criteria, null, 1)}`,
    metrics
      ? "Факты из аудио (пословные таймстампы Whisper):\n" +
        JSON.stringify(metrics, null, 1) +
        "\n\nОпирайся на них при оценке фонетики: паузы свыше " +
        metrics.pauseLimit +
        " с считаются необоснованными, WER - отклонение расшифровки от исходного текста (запинки, пропуски, перестановки слов)."
      : "",
    `Расшифровка ответа ученика:`,
    transcript,
  ]
    .filter(Boolean)
    .join("\n\n");
  return aiJSON({ system, prompt, name: "oral-grade" });
}