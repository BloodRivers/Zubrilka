export default function Legal({ doc }) {
  const { t } = useTheme();
  const contentRef = useRef(null);
  const [read, setRead] = useState(false);
  const readKey = `zubrilka:read:${doc}:${auth.currentUser?.uid ?? ""}`;

  useEffect(() => {
    setRead(localStorage.getItem(readKey) === "1");
    const el = contentRef.current?.closest?.(".scrollarea");
    if (!el) return;
    const markIfRead = () => {
      if (el.scrollTop + el.clientHeight >= el.scrollHeight - 16) {
        localStorage.setItem(readKey, "1");
        setRead(true);
      }
    };
    el.addEventListener("scroll", markIfRead, { passive: true });
    markIfRead();
    return () => el.removeEventListener("scroll", markIfRead);
  }, [readKey]);

  const items = doc === "terms" ? TERMS : doc === "privacy" ? PRIVACY : COOKIES;
  return (
    <div ref={contentRef}>
      <div style={{ color: t.sub, fontSize: 13, marginBottom: 20, lineHeight: 1.5 }}>
        Дата последнего обновления: {new Date().toLocaleDateString("ru-RU")}
      </div>
      {items.map((s) => (
        <div
          key={s.h}
          style={{ marginBottom: 20, borderBottom: `1px solid ${t.border}`, paddingBottom: 20 }}
        >
          <div style={{ color: t.text, fontSize: 17, fontWeight: 600, marginBottom: 8 }}>{s.h}</div>
          {s.p.map((p, i) => (
            <div key={i} style={{ color: t.sub, fontSize: 14, lineHeight: 1.55, marginBottom: 6 }}>
              {p}
            </div>
          ))}
        </div>
      ))}
      <div
        style={{
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          gap: 8,
          padding: "16px 0 8px",
          color: read ? t.inv : t.sub,
          fontSize: 14,
          fontWeight: 600,
        }}
      >
        {read ? (
          <>
            <Check size={18} /> Текст прочитан
          </>
        ) : (
          "Прокрути до конца"
        )}
      </div>
    </div>
  );
}
